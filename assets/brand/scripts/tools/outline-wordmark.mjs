#!/usr/bin/env node
// One-off tool: outlines the SwarmLoom logotype from the committed Bricolage Grotesque Bold
// (SIL OFL 1.1) font into SVG path data and writes scripts/lib/glyphs.ts.
//
// fontkit is intentionally not a repository dependency: the outlines are static artwork and only
// need regenerating when the logotype changes. Run with a temporary fontkit install:
//
//   npm i --prefix /tmp/fk fontkit@2 && \
//   FONTKIT_ENTRY=/tmp/fk/node_modules/fontkit/dist/module.mjs node assets/brand/scripts/tools/outline-wordmark.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const entry = process.env.FONTKIT_ENTRY;
if (!entry) {
  console.error("Set FONTKIT_ENTRY to fontkit's ESM entry (see the header of this file).");
  process.exit(1);
}
const fontkit = await import(pathToFileURL(entry).href);
const fontPath = join(here, "../../fonts/BricolageGrotesque-Bold.latin.woff2");
const font = fontkit.create(readFileSync(fontPath));

/** Em size the glyphs are outlined at; consumers scale from here. */
const SIZE = 100;
/** Tracking applied between glyphs, in SIZE units (tight display setting). */
const TRACKING = -3;
const TEXT = "SwarmLoom";

const scale = SIZE / font.unitsPerEm;
const round = (n) => Math.round(n * 100) / 100;
const OPS = { moveTo: "M", lineTo: "L", quadraticCurveTo: "Q", bezierCurveTo: "C", closePath: "Z" };

const run = font.layout(TEXT);
let pen = 0;
const glyphs = run.glyphs.map((glyph, i) => {
  const pos = run.positions[i];
  const x = pen + pos.xOffset * scale;
  // Path relative to the glyph origin, y-down with the baseline at 0.
  const d = glyph.path.commands
    .map((c) => OPS[c.command] + c.args.map((v, k) => round(k % 2 === 0 ? v * scale : -v * scale)).join(" "))
    .join("");
  pen += pos.xAdvance * scale + TRACKING;
  return { ch: String.fromCodePoint(...glyph.codePoints), x: round(x), advance: round(pos.xAdvance * scale), d };
});

const metrics = {
  size: SIZE,
  tracking: TRACKING,
  width: round(pen - TRACKING),
  capHeight: round(font.capHeight * scale),
  xHeight: round(font.xHeight * scale),
  ascent: round(font.ascent * scale),
  descent: round(font.descent * scale),
};

const out = `// Generated by tools/outline-wordmark.mjs from Bricolage Grotesque Bold (SIL OFL 1.1). Do not edit.
// Coordinates: em size ${SIZE}, y-down, baseline at y = 0, x relative to the glyph origin.

/** One outlined glyph of the logotype. */
export interface Glyph {
  /** Character the glyph renders. */
  ch: string;
  /** Pen position of the glyph origin, including kerning and tracking. */
  x: number;
  /** Horizontal advance. */
  advance: number;
  /** Outline path data relative to the glyph origin. */
  d: string;
}

export const LOGOTYPE_METRICS = ${JSON.stringify(metrics, null, 2)} as const;

export const LOGOTYPE_GLYPHS: readonly Glyph[] = ${JSON.stringify(glyphs, null, 2)};
`;
writeFileSync(join(here, "../lib/glyphs.ts"), out);
console.log(`wrote ${glyphs.length} glyphs, width ${metrics.width}`);
